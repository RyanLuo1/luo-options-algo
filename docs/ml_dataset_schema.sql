-- ============================================================================
-- ml_dataset — systematic setup+outcome records for ML training
-- ============================================================================
-- Purpose: a single, clean, single-purpose table that IS the ML training set.
-- Every row = one Call Spread Risk Reversal setup observed at a moment in time,
-- plus the realized outcome (filled in later at expiration).
--
-- Written to by BOTH:
--   * the backtester  (source = 'backtest')        — historical replay
--   * the daily sector scan (source = 'live_open' / 'live_close') — forward
--
-- Kept entirely separate from `tradebook` and `trade_outcomes`:
--   * tradebook = discretionary trades the user actually chose (selection-biased)
--   * ml_dataset = systematic, unbiased best-per-sector picks (clean for ML)
-- No foreign keys into tradebook. Do not mix.
--
-- CARDINAL RULE: every feature column is the value AS IT WAS AT SCAN TIME.
-- Never backfill a feature with future information. Only the `outcome_*`
-- columns are populated after the fact.
-- ============================================================================

create table if not exists ml_dataset (

    -- ---- identity / provenance -------------------------------------------
    id                      uuid primary key default gen_random_uuid(),
    created_at              timestamptz not null default now(),

    source                  text not null
        check (source in ('backtest', 'live_open', 'live_close')),
    -- backtest    = generated by historical replay
    -- live_open   = daily scan ~30 min after market open
    -- live_close  = daily scan ~30 min before market close

    scan_date               date not null,        -- the trading day this setup was observed
    scan_timestamp          timestamptz not null, -- exact observation time (delayed-data aware)
    sector                  text not null,         -- GICS-style sector (the grouping key)
    ticker                  text not null,
    is_best_in_sector       boolean not null default true,
    -- true = this was THE top-ranked setup for its sector in this scan slot.
    -- (Kept as a column rather than implied, so you can optionally log runners-up
    --  later without changing the schema — see note at bottom.)

    -- ---- the setup (three legs) ------------------------------------------
    expiration              date not null,
    weeks_to_expiration     integer,              -- weeks bucket used by the screener
    days_to_expiration      integer not null,     -- precise DTE at scan time (feature)

    leg_a_strike            numeric not null,     -- long call  (you pay)
    leg_a_prem              numeric not null,
    leg_a_delta             numeric not null,

    leg_b_strike            numeric not null,     -- short call (you collect)
    leg_b_prem              numeric not null,
    leg_b_delta             numeric not null,

    leg_c_strike            numeric not null,     -- short put  (you collect)
    leg_c_prem              numeric not null,
    leg_c_delta             numeric not null,

    -- ---- derived setup metrics (the algorithm's own outputs) -------------
    net_premium             numeric not null,     -- credit at entry (B + C - A)
    spread_width            numeric not null,     -- leg_b_strike - leg_a_strike
    score                   numeric not null,     -- net_premium / spread_width
    p_max_profit            numeric not null,     -- (1 - B delta) * (1 - C delta)

    -- ---- underlying / valuation at scan time -----------------------------
    underlying_price_at_scan numeric not null,    -- live (delayed) spot
    fair_value              numeric,              -- model price (distinct from spot)
    moneyness_a             numeric,              -- underlying / leg_a_strike (feature)

    -- ---- market context at scan time (features) --------------------------
    vix                     numeric,
    spy_price               numeric,
    -- room to grow: realized vol, IV rank, sector ETF move, etc.

    -- ---- event proximity at scan time (features) -------------------------
    days_to_earnings        integer,              -- null if unknown / none in window
    days_to_next_fomc       integer,
    days_to_next_cpi        integer,
    days_to_next_macro      integer,              -- nearest of FOMC/CPI/PPI/NFP
    earnings_before_expiry  boolean,              -- does earnings fall before expiration?

    -- ---- OUTCOME (NULL until the trade expires; filled by backfill) ------
    outcome_filled          boolean not null default false,
    outcome_type            text
        check (outcome_type is null or outcome_type in (
            'expired_credit_only',
            'expired_sweet_spot',
            'expired_capped',
            'expired_partial',
            'expired_breakeven',
            'expired_loss'
        )),
    stock_price_at_expiration numeric,
    realized_pnl            numeric,              -- per share
    pnl_per_contract        numeric,              -- realized_pnl * 100
    max_profit_per_contract numeric,              -- (net_premium + spread_width) * 100
    capture_pct             numeric,              -- pnl / max  (wins only; null for losses)
    outcome_filled_at       timestamptz,

    -- ---- bookkeeping ------------------------------------------------------
    notes                   text
);

-- ---- indexes (query patterns the ML/analytics work will use) -------------
create index if not exists idx_ml_dataset_scan_date   on ml_dataset (scan_date);
create index if not exists idx_ml_dataset_sector      on ml_dataset (sector);
create index if not exists idx_ml_dataset_source      on ml_dataset (source);
create index if not exists idx_ml_dataset_ticker      on ml_dataset (ticker);
create index if not exists idx_ml_dataset_unfilled    on ml_dataset (outcome_filled)
    where outcome_filled = false;   -- fast lookup of trades still awaiting outcome

-- ---- de-dup guard --------------------------------------------------------
-- Prevents logging the identical setup twice for the same scan slot
-- (e.g. re-running a backtest day, or a double daily scan). Tune the columns
-- if your definition of "the same observation" differs.
create unique index if not exists uniq_ml_dataset_observation
    on ml_dataset (source, scan_date, sector, ticker, expiration,
                   leg_a_strike, leg_b_strike, leg_c_strike);

-- ---- RLS -----------------------------------------------------------------
-- This is system-generated research data, not user-owned. Lock it down so it
-- is only written/read by the service role (the scanner / backtester /
-- backfill jobs), not by end users. Adjust to your auth model.
alter table ml_dataset enable row level security;
-- (No public policies defined => only the service role key can touch it.)

-- ============================================================================
-- NOTES / DECISIONS
-- ============================================================================
-- 1. WHY is_best_in_sector instead of only logging the single best:
--    You said "best per sector" (40/day). That's is_best_in_sector = true.
--    But keeping it as a flag means if you later decide the model needs the
--    FULL distribution (winners AND the mediocre runners-up it rejected),
--    you can log the top-N per sector with the flag distinguishing them —
--    without a schema migration. The model genuinely benefits from seeing
--    bad setups too, so this leaves that door open cheaply.
--
-- 2. NO-LEAKAGE DISCIPLINE: every column above the OUTCOME block must be
--    computed from data available AT scan_timestamp. In the backtester this
--    means using point-in-time historical chains and prices, never future
--    bars. A backtest that peeks ahead will look brilliant and mean nothing.
--
-- 3. DELAYED DATA: your plan is 15-min delayed. underlying_price_at_scan and
--    the leg premiums reflect ~15 min before scan_timestamp. That's a
--    consistent, honest basis for research — just never treat these as live
--    executable fills.
--
-- 4. OUTCOME backfill: a separate job (sibling to backfill_outcomes.py but
--    writing HERE, not to trade_outcomes) fills the outcome_* columns once
--    scan_date's expiration has passed. capture_pct stays NULL for losses
--    (matching the corrected convention in view_outcomes.py).
--
-- 5. FEATURE GROWTH: add new feature columns as nullable; never repurpose an
--    existing one. The model can ignore nulls; renaming/reusing breaks history.
-- ============================================================================